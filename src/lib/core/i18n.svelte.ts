// Lightweight i18n with Svelte 5 reactivity — no dependencies

const i18n = $state({ lang: localStorage.getItem('tmux_locale') || (navigator.language?.startsWith('zh') ? 'zh' : 'en') });

export { i18n };

/** The document speaks the UI's language (board #97): index.html ships
 * `lang="en"`, and Han-unified codepoints rendered by a FALLBACK font pick
 * their regional glyph variant by that tag — with `en` (or a JP-preferring
 * fontconfig default) Chinese text drew Japanese-variant shapes ("不像是标准
 * 的简体中文字"). `zh-CN` makes every fallback resolve to Simplified forms;
 * the guard keeps the module loadable under node --test. */
function applyDocLang(l: string) {
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
}
applyDocLang(i18n.lang);

export function setLocale(l: 'en' | 'zh') {
  i18n.lang = l;
  localStorage.setItem('tmux_locale', l);
  applyDocLang(l);
}

/** CONTENT language for a piece of user/agent text (board #97, round two):
 * a Chinese message in an ENGLISH UI still rendered Japanese-variant Han
 * (骨/直/门…), because the document lang says `en` and the glyph variant of a
 * fallback face follows the nearest lang. Content that contains Han is
 * therefore tagged itself — `lang={hanLang(text)}` — independent of the UI
 * language. SC is this product's Han default; `undefined` leaves non-Han
 * text untagged so the attribute only appears where it says something. */
export function hanLang(s: string): 'zh-CN' | undefined {
  return /\p{Script=Han}/u.test(s) ? 'zh-CN' : undefined;
}

