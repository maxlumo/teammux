import java.io.File
import javax.inject.Inject
import org.apache.tools.ant.taskdefs.condition.Os
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ProjectLayout
import org.gradle.api.logging.LogLevel
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.TaskAction
import org.gradle.process.ExecOperations

// Configuration-cache-safe rewrite of Tauri's generated BuildTask.
//
// Upstream (tauri-apps/tauri's android-studio-script template) reaches for
// `project.exec { }`, `project.projectDir`, and `project.logger` from inside
// @TaskAction. Gradle 8's configuration cache rejects any access to
// Task.project at execution time, which made the build fail outright when
// the configuration cache is enabled globally (as it is in our
// ~/.gradle/gradle.properties).
//
// Fix: inject ExecOperations and ProjectLayout via @Inject (the officially
// supported, cache-safe way to run external processes and read project
// paths from a task) and use DefaultTask's own `logger` property (which is
// the task's logger, not the project's, and is cache-safe).
//
// This file is generated by `tauri android init`. If you regenerate the
// Android project, this patch will be overwritten — re-apply from
// docs/design-docs/features/android-platform.md (Lessons Learned).
open class BuildTask @Inject constructor(
    private val execOps: ExecOperations,
    private val layout: ProjectLayout,
) : DefaultTask() {
    @Input
    var rootDirRel: String? = null
    @Input
    var target: String? = null
    @Input
    var release: Boolean? = null

    @TaskAction
    fun assemble() {
        val executable = """pnpm""";
        try {
            runTauriCli(executable)
        } catch (e: Exception) {
            if (Os.isFamily(Os.FAMILY_WINDOWS)) {
                // Try different Windows-specific extensions
                val fallbacks = listOf(
                    "$executable.exe",
                    "$executable.cmd",
                    "$executable.bat",
                )

                var lastException: Exception = e
                for (fallback in fallbacks) {
                    try {
                        runTauriCli(fallback)
                        return
                    } catch (fallbackException: Exception) {
                        lastException = fallbackException
                    }
                }
                throw lastException
            } else {
                throw e;
            }
        }
    }

    fun runTauriCli(executable: String) {
        val rootDirRel = rootDirRel ?: throw GradleException("rootDirRel cannot be null")
        val target = target ?: throw GradleException("target cannot be null")
        val release = release ?: throw GradleException("release cannot be null")
        val args = listOf("tauri", "android", "android-studio-script");

        val projectDir = layout.projectDirectory.asFile
        val taskLogger = logger
        execOps.exec {
            workingDir(File(projectDir, rootDirRel))
            executable(executable)
            args(args)
            if (taskLogger.isEnabled(LogLevel.DEBUG)) {
                args("-vv")
            } else if (taskLogger.isEnabled(LogLevel.INFO)) {
                args("-v")
            }
            if (release) {
                args("--release")
            }
            args(listOf("--target", target))
        }.assertNormalExitValue()
    }
}
