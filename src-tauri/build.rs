fn main() {
    // With `gui` on, tauri-build does everything: ACL/permission codegen, the
    // mobile project glue, and the `desktop` / `mobile` cfg aliases.
    #[cfg(feature = "gui")]
    tauri_build::build();

    // With `gui` off there is no `tauri` dependency, so tauri_build::build()
    // panics on the `cargo:dev` instruction that tauri's own build script would
    // have emitted. Nothing it generates is needed for the headless binaries —
    // except the two cfg aliases, which src/lib.rs gates modules on. Emit them
    // here with the same rule tauri-build uses (mobile == android | ios).
    #[cfg(not(feature = "gui"))]
    {
        println!("cargo:rustc-check-cfg=cfg(desktop)");
        println!("cargo:rustc-check-cfg=cfg(mobile)");
        let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
        if target_os == "android" || target_os == "ios" {
            println!("cargo:rustc-cfg=mobile");
        } else {
            println!("cargo:rustc-cfg=desktop");
        }
    }

    // The build's identity (board #368): the checkout's short commit and the
    // UTC minute this build ran, baked in for `build_info`. 'dev'/'unknown'
    // when git or the clock is unavailable; never a failed build.
    build_identity();

    // `embed-ui` (board #323): the web UI's dist/ becomes a sorted
    // (path, include_bytes!) table the gateway serves; nothing is read from
    // disk at run time. Any change under dist/ rebuilds.
    if std::env::var_os("CARGO_FEATURE_EMBED_UI").is_some() {
        embed_ui();
    }
}

fn embed_ui() {
    let manifest = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = manifest.parent().unwrap().join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    if !dist.join("index.html").is_file() {
        panic!("embed-ui: {} has no index.html — run `npm run build` first", dist.display());
    }
    let mut files = Vec::new();
    let mut stack = vec![dist.clone()];
    while let Some(dir) = stack.pop() {
        for e in std::fs::read_dir(&dir).unwrap() {
            let e = e.unwrap();
            let p = e.path();
            // Never follow a link: one could pull a file from outside dist/
            // into a public binary, or loop. A normal `vite build` has none.
            let kind = e.file_type().unwrap();
            if kind.is_symlink() {
                panic!("embed-ui: {} is a symbolic link — dist/ must hold only regular files", p.display());
            }
            if kind.is_dir() {
                stack.push(p);
            } else if kind.is_file() {
                let rel = p.strip_prefix(&dist).unwrap().to_string_lossy().replace('\\', "/");
                files.push((rel, p.canonicalize().unwrap()));
            }
        }
    }
    files.sort();
    let mut out = String::from("/// Generated by build.rs from dist/ (feature embed-ui). Sorted by path.\npub static FILES: &[(&str, &[u8])] = &[\n");
    for (rel, abs) in &files {
        out.push_str(&format!("    ({rel:?}, include_bytes!({:?})),\n", abs.to_string_lossy()));
    }
    out.push_str("];\n");
    let dest = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("ui_embed.rs");
    std::fs::write(dest, out).unwrap();
}

/// `git <args>` in this package's directory, trimmed; None on any failure.
fn git(args: &[&str]) -> Option<String> {
    let out = std::process::Command::new("git")
        .args(args)
        .current_dir(std::env::var("CARGO_MANIFEST_DIR").ok()?)
        .output()
        .ok()?;
    let text = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (out.status.success() && !text.is_empty()).then_some(text)
}

/// Seconds since the epoch as `YYYY-MM-DD HH:MM` UTC (the civil-from-days
/// algorithm; no date crate for one string).
fn utc_minute(secs: u64) -> String {
    let (days, rem) = ((secs / 86_400) as i64, secs % 86_400);
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!("{year:04}-{month:02}-{day:02} {:02}:{:02}", rem / 3_600, rem % 3_600 / 60)
}

fn build_identity() {
    let sha = git(&["rev-parse", "--short=8", "HEAD"]).filter(|s| s.chars().all(|c| c.is_ascii_hexdigit()));
    println!("cargo:rustc-env=TMM_GIT_SHA={}", sha.as_deref().unwrap_or("dev"));
    let built = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| utc_minute(d.as_secs()))
        .unwrap_or_else(|_| "unknown".into());
    println!("cargo:rustc-env=TMM_BUILD_TIME={built}");
    // Declaring any rerun-if-changed turns off cargo's default (any package
    // file), so say both: a moved HEAD (a new commit) and the sources.
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=Cargo.toml");
    if let Some(head) = git(&["rev-parse", "--git-path", "HEAD"]) {
        println!("cargo:rerun-if-changed={head}");
    }
    if let Some(branch) = git(&["symbolic-ref", "-q", "HEAD"]) {
        if let Some(path) = git(&["rev-parse", "--git-path", &branch]) {
            println!("cargo:rerun-if-changed={path}");
        }
    }
    if let Some(packed) = git(&["rev-parse", "--git-path", "packed-refs"]) {
        println!("cargo:rerun-if-changed={packed}");
    }
}
